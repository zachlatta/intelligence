-- Accounts. Everything an account can read is scoped to it, in Postgres itself: each account reads
-- through its own login role (db.AccountRole), and row-level security shows that role only its own
-- rows. The app writes as the tables' owner, which row-level security does not limit.
--
-- An account owns the dev boxes it holds keys for (devbox_keys), and with them everything the
-- boxes report: workspaces, agents, transcripts, commands, resources, and the plan logins they read.

CREATE TABLE accounts (
    id                  bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username            text NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9][a-z0-9_-]{0,31}$'),
    password_hash       text NOT NULL, -- argon2id, PHC string
    role_name           text NOT NULL UNIQUE, -- the login role it reads as
    created_at          timestamptz NOT NULL DEFAULT now(),
    password_changed_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE accounts IS 'who can sign in; each account reads only its own rows, through its own role';

-- A signed-in browser. The cookie holds a random token; only its hash is kept.
CREATE TABLE sessions (
    token_hash   text PRIMARY KEY, -- sha256 of the cookie's token, hex
    account_id   bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    created_at   timestamptz NOT NULL,
    expires_at   timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL
);
CREATE INDEX sessions_account ON sessions (account_id);

-- Each dev box's key: what it streams with. The box belongs to the key's account. Only the hash is kept.
CREATE TABLE devbox_keys (
    box          text PRIMARY KEY,
    account_id   bigint NOT NULL REFERENCES accounts ON DELETE CASCADE,
    key_hash     text NOT NULL UNIQUE, -- sha256 of the key, hex
    created_at   timestamptz NOT NULL,
    last_used_at timestamptz
);
CREATE INDEX devbox_keys_account ON devbox_keys (account_id);

-- A box asking to join: it shows a code, a signed-in account enters it (claims it), and the box,
-- proving it asked with its secret, collects its key. Only hashes of the code and secret are kept.
CREATE TABLE devbox_enrollments (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    box         text NOT NULL,
    code_hash   text NOT NULL UNIQUE,
    secret_hash text NOT NULL,
    created_at  timestamptz NOT NULL,
    expires_at  timestamptz NOT NULL,
    account_id  bigint REFERENCES accounts ON DELETE CASCADE, -- who claimed it; null until then
    claimed_at  timestamptz
);

-- The account the current session reads as: the one whose role logged in. session_user, not
-- current_user: inside this function current_user is its owner, and SET ROLE cannot change
-- session_user. Null for any other role, which so reads no account's rows.
CREATE FUNCTION current_account_id() RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp
AS $$ SELECT id FROM public.accounts WHERE role_name = session_user $$;

ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON accounts FOR SELECT USING (id = current_account_id());

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['sessions', 'devbox_keys', 'devbox_enrollments'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY own_rows ON %I FOR SELECT USING (account_id = current_account_id())', t);
    END LOOP;
    FOREACH t IN ARRAY ARRAY['workspaces', 'agents', 'transcripts', 'transcript_entries', 'commands', 'host_minutes',
        'agent_minutes', 'oom_kills', 'host_probes', 'usage_active', 'usage_sources'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('CREATE POLICY own_boxes ON %I FOR SELECT USING (box IN (SELECT k.box FROM devbox_keys k WHERE k.account_id = current_account_id()))', t);
    END LOOP;
END $$;

ALTER TABLE devboxes ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_boxes ON devboxes FOR SELECT
    USING (name IN (SELECT k.box FROM devbox_keys k WHERE k.account_id = current_account_id()));

-- A plan login is the account's when one of its boxes read it or used it (usage_sources and
-- usage_active are themselves scoped to the account's boxes).
ALTER TABLE usage_accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_logins ON usage_accounts FOR SELECT USING (
    EXISTS (SELECT 1 FROM usage_sources s WHERE s.provider = usage_accounts.provider AND s.account = usage_accounts.account)
    OR EXISTS (SELECT 1 FROM usage_active a WHERE a.provider = usage_accounts.provider AND a.account = usage_accounts.account));

ALTER TABLE usage_readings ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_logins ON usage_readings FOR SELECT USING (
    EXISTS (SELECT 1 FROM usage_accounts a WHERE a.provider = usage_readings.provider AND a.account = usage_readings.account));

